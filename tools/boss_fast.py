#!/usr/bin/env python3
# boss_fast.py: precomputed OAM words for BossDraw's fast path (whole boss on screen).
# Per view (chase, cockpit) x arm pose (bit0 left raised, bit1 right raised): 2*NCELL entries of
#   word (dy<<8)+dx  (added to (b_sy<<8)+b_sx in one 16-bit add)
#   word tile | (attr << 8)   (palette 7, h-flip on the right half; priority ORed in at runtime)
import re
src = open("assets/boss.inc").read()
def cells(name):
    blk = src.split(name + ":")[1].split("\n")[1:]
    out = []
    for l in blk:
        m = re.match(r"\s*\.word (.*)", l)
        if not m: break
        out.append([int(v.strip().lstrip("$"), 16) for v in m.group(1).split(",")])
    return out
s = lambda v: v - 65536 if v >= 32768 else v
lines = ["; generated by tools/boss_fast.py from boss.inc (BossDraw fast path)"]
xs, ys = [], []
for view in ("chase", "cock"):
    cs = cells("BossCells_" + view)
    for arm in range(4):
        lines.append(f"BossFast_{view}_{arm}:")
        for dx, dy, t0, t1 in cs:
            dx, dy = s(dx), s(dy)
            for side in (0, 1):
                raised = (arm >> side) & 1
                t = t1 if raised else t0
                x = dx if side == 0 else -dx - 16
                xs += [x, x + 16]; ys += [dy, dy + 16]
                off = (dy * 256 + x) & 0xFFFF
                attr = 0x0E | (t >> 8 & 1) | (0x40 if side else 0)
                lines.append(f"  .word ${off:04X}, ${(t & 0xFF) | attr << 8:04X}")
n = len(cells("BossCells_chase")) * 2
lines += [f"BOSS_FAST_N = {n}", f"BOSS_FAST_X0 = {-min(xs)}", f"BOSS_FAST_X1 = {256 - max(xs)}",
          f"BOSS_FAST_Y0 = {-min(ys)}", f"BOSS_FAST_Y1 = {224 - max(ys)}"]
open("assets/boss_fast.inc", "w").write("\n".join(lines) + "\n")
print("boss_fast.inc:", n, "pieces; fast if", -min(xs), "<= sx <=", 256 - max(xs), ",", -min(ys), "<= sy <=", 224 - max(ys))
